export function currentLocale() {
  return document.documentElement.dataset.locale === "en" ? "en" : "zh";
}

export function t(key, vars = {}) {
  let value = TEXT[currentLocale()]?.[key] ?? TEXT.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}

export function setLocale(locale) {
  const next = locale === "en" ? "en" : "zh";
  document.documentElement.dataset.locale = next;
  document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  try { localStorage.setItem("pi-trace-locale", next); } catch {}
}

export function applyStaticText() {
  document.querySelectorAll("[data-text]").forEach((node) => {
    node.textContent = t(node.dataset.text);
  });
  const search = document.getElementById("globalSearch");
  if (search) search.placeholder = t("searchPlaceholder");
  const provider = document.getElementById("providerFilter")?.options?.[0];
  const status = document.getElementById("statusFilter")?.options;
  if (provider) provider.textContent = t("allProviders");
  if (status?.[0]) status[0].textContent = t("allStatuses");
  if (status?.[1]) status[1].textContent = t("streaming");
  if (status?.[2]) status[2].textContent = t("success");
  if (status?.[3]) status[3].textContent = t("failed");
  const localeButton = document.getElementById("localeButton");
  if (localeButton) localeButton.textContent = currentLocale() === "zh" ? "中" : "EN";
}
